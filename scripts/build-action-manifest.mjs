// Writes lib/actions/manifest.js: for every action in registry.js's order, its name, the file of lib/actions that defines it, its
// HTTP method and path, and its key permission. lib/actions/lazy.js and the REST API route from it, so a request loads one file of
// actions instead of all of them. Run it after adding or changing an action's name, method, path or permission; the test in
// tests/action-manifest.test.mjs fails until the file matches.
//   node --import ./tests/setup/register.mjs scripts/build-action-manifest.mjs
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { ACTION_FILES } from "../lib/actions/groups.js";
import { ACTIONS, DASHBOARD_ONLY_ACTIONS } from "../lib/actions/registry.js";

export async function buildManifestRows() {
	const fileOf = new Map();
	for (const [file, { exportName, load }] of Object.entries(ACTION_FILES)) {
		for (const action of (await load())[exportName]) fileOf.set(action.name, file);
	}
	// The actions with a route and a tool, in the registry's order, then the dashboard-only ones, which runAction can load by name.
	return [...ACTIONS, ...DASHBOARD_ONLY_ACTIONS].map((action) => [action.name, fileOf.get(action.name), action.http.method, action.http.path, action.permission, Boolean(action.dashboardOnly)]);
}

export function renderManifest(rows) {
	return `// GENERATED by scripts/build-action-manifest.mjs from registry.js: do not edit by hand. [name, file in groups.js, method, path, permission, dashboardOnly].
export const ACTION_MANIFEST = [
${rows.map((row) => `\t${JSON.stringify(row)},`).join("\n")}
];
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
	const rows = await buildManifestRows();
	writeFileSync(fileURLToPath(new URL("../lib/actions/manifest.js", import.meta.url)), renderManifest(rows));
	console.log(`build-action-manifest: ${rows.length} actions`);
}
