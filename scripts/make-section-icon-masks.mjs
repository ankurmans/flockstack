// Writes lib/section-icon-masks.js: each section icon (lib/section-icons.js) as a 48 by 48 coverage mask, one byte a pixel, base64.
// The email's icon PNGs and the share card's icons are made from these at run time (lib/section-icon-png.js): next/og draws an SVG
// image blank on Cloudflare Workers, so nothing there draws SVG. sharp (installed with Next.js) draws them here, at build time.
// Run it again after changing an icon's drawing:
//
//     node scripts/make-section-icon-masks.mjs
import { writeFile } from "node:fs/promises";
import sharp from "sharp";
import { SECTION_ICON_KEYS, sectionIconSvg } from "../lib/section-icons.js";

const SIZE = 48;

const lines = [];
for (const key of SECTION_ICON_KEYS) {
	const svg = Buffer.from(sectionIconSvg(key, { size: SIZE, color: "#000000" }));
	const { data, info } = await sharp(svg, { density: 72 * 4 }).resize(SIZE, SIZE).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
	const mask = Buffer.alloc(SIZE * SIZE);
	for (let pixel = 0; pixel < SIZE * SIZE; pixel++) mask[pixel] = data[pixel * info.channels + 3];
	lines.push(`\t${JSON.stringify(key)}: "${mask.toString("base64")}",`);
}

await writeFile(
	new URL("../lib/section-icon-masks.js", import.meta.url),
	`// GENERATED by scripts/make-section-icon-masks.mjs from lib/section-icons.js: do not edit by hand.\nexport const MASK_SIZE = ${SIZE};\nexport const SECTION_ICON_MASKS = {\n${lines.join("\n")}\n};\n`
);
